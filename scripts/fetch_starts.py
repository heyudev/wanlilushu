def main():
    nodes = load("data/route.json")["nodes"]
    out = []
    for name, ll in CITIES.items():
        same = [n for n in nodes if haversine(n["ll"], ll) < 25]
        if same:
            out.append(dict(name=name, ll=list(ll), entry=same[0]["id"], km=0, h=0, hw=0))
            continue
        near = sorted(nodes, key=lambda n: haversine(n["ll"], ll))[:3]
        best = None
        for n in near:
            r = route(list(ll), n["ll"])
            if best is None or r["km"] < best[1]["km"]:
                best = (n, r)
        n, r = best
        out.append(dict(name=name, ll=list(ll), entry=n["id"], km=r["km"], h=r["h"], hw=r["hw"]))
        print(f"{name} → {n['n']} {r['km']}km")
    save("data/generated/starts.json", out, indent=1)


if __name__ == "__main__":
    main()
