def geocode(query):
    url = "https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode(
        {"q": query, "format": "json", "limit": 3, "countrycodes": "cn"})
    time.sleep(1.1)
    return get_json(url)


def main():
    D = load("data/route.json")
    old = {n["id"]: n for n in D["nodes"]}
    out = []
    for nid in ORDER:
        if nid in old:
            n = dict(old[nid])
        else:
            (name, prov, seg, q, la, lo, nights, best, star, sleep, kind, wiki, food, tip, about) = NEW[nid]
            ll = [la, lo]
            hits = geocode(q)
            if hits:
                cand = [float(hits[0]["lat"]), float(hits[0]["lon"])]
                d = haversine(cand, ll)
                if d < 40:
                    ll = [round(cand[0], 4), round(cand[1], 4)]
                else:
                    print(f"  ! {nid}: geocode {q} is {d:.0f} km from expected, keeping rough position")
            else:
                print(f"  ! {nid}: no geocode for {q}, keeping rough position")
            n = dict(id=nid, n=name, p=prov, seg=seg, ll=ll, nights=nights, best=best, star=star, sleep=sleep,
                     wiki=wiki, food=food, tip=tip, dog="", ex=[], tags=[], about=about, kind=kind)
        n.setdefault("kind", KIND.get(nid, "nature"))
        if nid in ABOUT:
            n["about"] = ABOUT[nid]
        n["base"] = nid in BASES
        out.append(n)
        print(nid, n["ll"])
    missing = set(ORDER) - set(old) - set(NEW)
    assert not missing, missing
    dropped = set(old) - set(ORDER)
    print("dropped:", dropped)
    # interest tags for new stops
    for n in out:
        if n["tags"]:
            continue
        t = []
        if n["kind"] in ("city", "town"):
            t.append("culture")
        if n["kind"] == "city":
            t += ["city", "food"]
        if n["kind"] in ("nature", "transit"):
            t.append("nature")
        n["tags"] = t
    D["nodes"] = out
    D["segs"] = [s for s in D["segs"]]
    save("data/route.json", D, indent=1)
    print(len(out), "stops;", sum(1 for n in out if n["base"]), "long-stay candidates")


